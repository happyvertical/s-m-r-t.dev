	<h3 id="route-auth">The fail-closed auth guard</h3>
	<p>
		Every generated CRUD and action handler calls <code>requireRouteAuth(locals, mutating)</code>
		before doing any work. It throws <code>401</code> unless the route is explicitly opted public,
		or <code>locals</code> carries a resolved, object-shaped principal
		(<code>locals.user</code>, <code>locals.session</code>, or the explicit
		<code>locals.smrtAuth === true</code> marker). Mutating verbs require auth even when reads are
		opted public. The full security model — what counts as a principal, how
		<code>@field</code> visibility works, and where your responsibilities begin — is on the
		<a href="/docs/security">Security</a> page.
	</p>
	<Callout variant="security" title="Generated routes are private by default">
		With no <code>api.public</code> set, the default is <code>false</code> and every route returns
		<code>401</code> until an authenticated principal is present. You opt in to public access
		deliberately, per object.
	</Callout>

	<h3 id="custom-methods">Custom-method routing</h3>
	<p>
		Any public method that is not one of the five CRUD actions (<code>list</code>,
		<code>get</code>, <code>create</code>, <code>update</code>, <code>delete</code>) becomes its
		own route. The <code>api.routes[name]</code> entry controls its HTTP method, URL path, and
		<strong>scope</strong>:
	</p>
	<ul>
		<li>
			<strong>Item scope</strong> (the default for instance methods) — routed under the
			<code>[id]</code> segment, e.g. <code>POST /products/[id]/restock</code>. The handler loads
			the instance with <code>collection.get(params.id)</code> before invoking your method.
		</li>
		<li>
			<strong>Collection scope</strong> — routed at the collection root, e.g.
			<code>GET /products/featured</code>. Collection-scoped routes require a
			<strong>static</strong> method; a non-static method declared with
			<code>scope: 'collection'</code> is skipped with a warning.
		</li>
	</ul>
	<CodeBlock code={customMethod} filename="src/lib/models/product.ts" />
	<p>
		The default URL segment is the method name (kebab-cased when the
		<code>kebabRoutes</code> option is on). An explicit
		<code>api.routes[name].path</code> always wins. Custom-action results are returned as
		<code>{`{ action, result }`}</code>, with the <code>result</code> recursively passed through
		<code>toPublicJSON()</code> so any returned objects still strip their sensitive fields.
	</p>

	<h2 id="four-surfaces">The four surfaces, side by side</h2>
	<p>From that one <code>Product</code> class you can now call into the same logic four ways:</p>
	<CodeBlock code={fourSurfaces} lang="text" />
	<p>
		The CLI, MCP, and SQL surfaces are exposed as Vite <em>virtual modules</em> —
		<code>smrt:cli</code>, <code>smrt:mcp</code>, and <code>smrt:schema</code> respectively —
		generated on import from the same manifest. (<code>smrt:routes</code>,
		<code>smrt:client</code>, <code>smrt:types</code>, and <code>smrt:manifest</code> are also
		available.) Only the REST routes are emitted as files on disk.
	</p>

	<h2 id="coherence">The CLI ↔ API coherence check</h2>
	<p>
		The generated CLI does not call your methods in-process — it invokes them <strong>over
		HTTP</strong>, through the generated API. So a CLI command for a method that has no API route
		would be dead on arrival. To catch that at build time,
		<code>validateCliIncludeAgainstApi()</code> runs during the build and <strong>throws</strong>
		if any class lists a command in <code>cli.include</code> that is not reachable via
		<code>api.include</code>.
	</p>
	<Callout variant="warning" title="Build fails on an unreachable CLI command">
		If you add <code>'archive'</code> to <code>cli.include</code> but never expose it through the
		API, the build stops with: <em>"…is declared in cli.include but is not exposed via the api."</em>
		Fix it by adding the method to <code>api.include</code>, or — if you really do invoke that CLI
		in-process with no HTTP — acknowledge it with
		<code>cli: {`{ skipApiCheck: true }`}</code>. The check is on by default and can be disabled
		globally with the plugin option <code>validateCliApiCoherence: false</code>.
	</Callout>

	<h2 id="trace">End to end</h2>
	<ol>
		<li>You author a <code>@smrt()</code> class with a <code>collection</code> name and fields.</li>
		<li>
			<code>smrtPlugin()</code> runs the <code>OxcScanner</code> over your <code>.ts</code> files on
			dev startup and build.
		</li>
		<li>The scan produces a manifest, written to <code>.smrt/manifest.json</code>.</li>
		<li>
			<code>generateSvelteKitRoutes()</code> writes <code>+server.ts</code> files under
			<code>src/routes/&lt;collection&gt;/</code>, each guarded by <code>requireRouteAuth</code>.
		</li>
		<li>
			The CLI, MCP, and SQL surfaces are served from <code>smrt:cli</code>,
			<code>smrt:mcp</code>, and <code>smrt:schema</code> virtual modules, all built from the same
			manifest.
		</li>
		<li>
			The build-time coherence check fails fast if a CLI command can't reach an API route.
		</li>
	</ol>
	<p>
		That is the entire codegen path. To go deeper on each object's fields, decorators, and
		lifecycle, see <a href="/docs/objects">Objects</a>; for the security defaults on the generated
		surface, see <a href="/docs/security">Security</a>.
	</p>


	<h2 id="step-1">1. You write the class</h2>
	<p>
		A SMRT object is a plain TypeScript class extending <code>SmrtObject</code>, annotated with
		<code>@smrt()</code>. The decorator config declares which surfaces to generate — here, four REST
		actions plus the CLI and MCP tool sets.
	</p>
	<CodeBlock code={sourceClass} filename="src/lib/models/product.ts" />

	<h2 id="step-2">2. The plugin scans it</h2>
	<p>
		Register <code>smrtPlugin()</code> in <code>vite.config.ts</code>. During
		<code>configResolved</code> (and <code>buildStart</code>), it calls its scanner over your source
		tree.
	</p>
	<CodeBlock code={viteConfig} filename="vite.config.ts" />
	<p>
		Scanning is handled by <code>@happyvertical/smrt-scanner</code>'s <code>OxcScanner</code>, a
		Rust-based <code>oxc-parser</code> AST pass. It walks your <code>.ts</code> files (it explicitly
		excludes <code>.svelte</code> files, since OXC chokes on <code>&lt;style&gt;</code> tags),
		reads each <code>@smrt()</code> class, and resolves inheritance. A scan error fails the build
		rather than silently emitting an empty manifest.
	</p>

	<h2 id="step-3">3. It builds the manifest</h2>
	<p>
		The scan produces a <em>manifest</em>: a description of every object — its fields, methods,
		decorator config, and collection name. The plugin writes it to
		<code>.smrt/manifest.json</code> so the CLI and other tools can discover your objects without
		re-scanning.
	</p>
	<Callout variant="note" title="The manifest is the single source">
		Every downstream surface is generated from the manifest, not from your source directly. That is
		why the REST API, CLI, MCP tools, and SQL schema can never drift apart — they are four
		projections of one description.
	</Callout>

	<h2 id="step-4">4. It generates the surfaces</h2>
	<p>
		With the manifest in hand, <code>generateSvelteKitRoutes()</code> writes the REST routes to
		disk, and the plugin registers virtual modules that materialize the other three surfaces on
		import.
	</p>


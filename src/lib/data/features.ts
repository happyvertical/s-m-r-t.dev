/**
 * Features (#361, slice A #362): the nine sections and forty-nine features the
 * front-page map, the section index pages and the feature showcases are
 * generated from. Supersedes the #358 `blocks.ts` seed, which stays until
 * slice E (#366) retires its consumers.
 *
 * A feature is a capability a builder does not write from scratch; its
 * `packages` are the smrt packages that supply it. Every `inTheBox` noun was
 * checked against the installed package's `AGENTS.md` for the release this
 * site documents (`SMRT_VERSION`), scratch-installing packages the site does
 * not depend on at that exact version. Mobile is the one exception: its
 * packages are source distributions, so its nouns come from the monorepo
 * `AGENTS.md` at the same tag.
 *
 * `reference` is the Docs URL the package page has after slice D (#365);
 * `source` is the package directory in the smrt monorepo at the installed tag.
 * `example` mounts a real playground entry (`playgrounds.ts`) where a package
 * ships one that shows the feature; otherwise it names a still under
 * `static/stills/features/`, generated by `scripts/generate-feature-stills.mjs`
 * with Acme Corp example data. `recipes` lists the planner recipe ids the
 * feature switches on; it is filled in when the planner mapping lands.
 */

import { SMRT_VERSION } from '$lib/version';

export type FeatureSectionId =
	| 'agents'
	| 'basics'
	| 'screens'
	| 'content'
	| 'messaging'
	| 'commerce'
	| 'operations'
	| 'marketing'
	| 'world';

export type FeatureExample =
	| {
			kind: 'playground';
			/** A `/playground?entry=<slug>` slug that `resolvePlaygroundSlug` accepts. */
			entry: string;
	  }
	| {
			kind: 'still';
			/** Path under `static/`, served as-is. */
			src: string;
	  };

export interface FeatureSection {
	id: FeatureSectionId;
	/** The one word on the map node. */
	word: string;
	/** The hover sentence, at most 12 words. */
	hint: string;
	/** Union of the packages behind the section's features, in first-use order. */
	packages: string[];
	reference: string;
	source: string;
}

export interface Feature {
	/** Slug; the route segment under /features/<section>/. */
	id: string;
	section: FeatureSectionId;
	/** The one word on the map node; two only where the name is two (HR is one). */
	word: string;
	/** The hover sentence and the showcase sentence, at most 12 words. */
	hint: string;
	/** Package slugs from `packages.ts`; the first is the primary package. */
	packages: string[];
	/** `/docs/reference/packages/<slug>` of the primary package. */
	reference: string;
	/** GitHub tree URL of the primary package at the installed tag. */
	source: string;
	example: FeatureExample;
	/** 3–5 nouns, each verified against the primary package's AGENTS.md. */
	inTheBox: string[];
	/** Planner recipe ids this feature switches on. */
	recipes: string[];
}

/**
 * Monorepo directories keep the `smrt-` prefix for the packages listed here
 * and drop it for every other package (`packages/chat`, `packages/approvals`).
 * Mirrors `sourceDirectory` in `PackageWorkbench.svelte`.
 */
const prefixedSourceDirectories = new Set([
	'smrt-android',
	'smrt-app-mcp',
	'smrt-dev-mcp',
	'smrt-ios',
	'smrt-mobile',
	'smrt-mobile-contract',
	'smrt-playground',
	'smrt-svelte',
	'smrt-ui',
	'smrt-web'
]);

export function packageSourceUrl(slug: string): string {
	const directory = prefixedSourceDirectories.has(slug) ? slug : slug.replace(/^smrt-/, '');
	return `https://github.com/happyvertical/smrt/tree/v${SMRT_VERSION}/packages/${directory}`;
}

export function packageReferenceUrl(slug: string): string {
	return `/docs/reference/packages/${slug}`;
}

function still(id: string): FeatureExample {
	return { kind: 'still', src: `/stills/features/${id}.svg` };
}

function playground(entry: string): FeatureExample {
	return { kind: 'playground', entry };
}

interface FeatureSeed {
	id: string;
	section: FeatureSectionId;
	word: string;
	hint: string;
	packages: string[];
	example: FeatureExample;
	inTheBox: string[];
	recipes?: string[];
}

function feature(seed: FeatureSeed): Feature {
	const [primary] = seed.packages;
	return {
		...seed,
		reference: packageReferenceUrl(primary),
		source: packageSourceUrl(primary),
		recipes: seed.recipes ?? []
	};
}


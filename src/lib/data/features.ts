export const featureSections: FeatureSection[] = sectionSeeds.map((seed) => {
	const packages = [
		...new Set(features.filter((item) => item.section === seed.id).flatMap((item) => item.packages))
	];
	const [primary] = packages;
	return {
		...seed,
		packages,
		reference: packageReferenceUrl(primary),
		source: packageSourceUrl(primary)
	};
});

/**
 * Published packages that are not a feature a builder adopts: developer tools,
 * templates, runtimes and the planner. `features.test.ts` requires every
 * package in `packages.ts` to appear in a feature or here, so the map can
 * never silently omit one. `smrt-gnode` is a stub and keeps its package page
 * only.
 */
export const toolingPackageSlugs: string[] = [
	'smrt-cli',
	'smrt-app-cli',
	'smrt-app-runtime',
	'smrt-config',
	'smrt-gnode',
	'smrt-planner',
	'smrt-template-site-static-json',
	'smrt-template-sveltekit',
	'smrt-vitest',
	'smrt-workbench'
];

export function getFeatureSection(id: string): FeatureSection | undefined {
	return featureSections.find((section) => section.id === id);
}

export function getFeature(id: string): Feature | undefined {
	return features.find((item) => item.id === id);
}

export function featuresInSection(section: FeatureSectionId): Feature[] {
	return features.filter((item) => item.section === section);
}

/** Route of a section index page. */
export function featureSectionPath(section: Pick<FeatureSection, 'id'>): string {
	return `/features/${section.id}`;
}

/** Route of a feature showcase page. */
export function featurePath(item: Pick<Feature, 'id' | 'section'>): string {
	return `/features/${item.section}/${item.id}`;
}

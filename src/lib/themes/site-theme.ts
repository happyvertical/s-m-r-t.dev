/**
 * The site's own smrt-ui theme (#401): pine green primary, brass secondary,
 * over warm neutral paper in light and green-black in dark.
 *
 * This is the app-level mechanism smrt-ui documents (`createTheme()` plus
 * `registerTheme()`, then `<ThemeProvider preset={id}>`), so every smrt-ui
 * component under the site's provider takes these tokens. Nothing here
 * overrides a component's internals, and the `smrt` preset is untouched.
 *
 * Both palettes are written out in full. `createTheme()` builds the dark
 * palette as `{ ...light, ...dark }`, so a key left out of `dark` would carry
 * its light value into the dark scheme; `site-theme.test.ts` holds the two key sets
 * equal and checks the text pairings for contrast.
 *
 * `src/lib/styles/site-theme.css` is this theme as static CSS, generated by
 * `site-theme.test.ts`. Edit a value here, then regenerate it:
 *   pnpm exec vitest run -u src/lib/themes
 */

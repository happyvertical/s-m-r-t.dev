export const siteTheme: Theme = {
	...createTheme({
		// A custom id is outside smrt-ui's built-in `ThemePreset` union; the
		// registry accepts any registered id.
		id: SITE_THEME_ID as ThemePreset,
		name: 'smrt site',
		light,
		dark,
		typography,
		// Written out so `--smrt-surface-sunken` is the approved sunken colour;
		// derived, it would be the lowest container, darker than the page in dark.
		surfaces: {
			light: {
				ground: light.background,
				panel: light.surface,
				control: light.surface,
				raised: light.surface,
				sunken: light.surfaceContainer,
				overlay: light.scrim
			},
			dark: {
				ground: dark.background,
				panel: dark.surface,
				control: dark.surfaceContainerHigh,
				raised: dark.surfaceContainerHigh,
				sunken: dark.surfaceContainer,
				overlay: dark.scrim
			}
		},
		fontFamily: BODY_FONT
	}),
	// `createTheme()` has no option for the mono face; `Theme` does.
	fontFamilyMono: MONO_FONT
};

registerTheme(siteTheme);

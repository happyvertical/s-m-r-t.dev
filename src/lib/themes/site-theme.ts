const display = (size: string, lineHeight: string, tracking: string) => ({
	size,
	lineHeight,
	weight: '700',
	tracking,
	fontFamily: DISPLAY_FONT
});
const body = (size: string, lineHeight: string, weight: string, tracking = '0') => ({
	size,
	lineHeight,
	weight,
	tracking,
	fontFamily: 'var(--smrt-font-family)'
});

